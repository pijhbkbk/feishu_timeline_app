import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

test.skip(!process.env.R28_RUNTIME_ROOT, 'Requires the explicit isolated native-auth runtime.');
const root = process.env.R28_RUNTIME_ROOT!;
for (const width of [1440, 1024, 390]) {
  test(`native accounts and new project/task routes at ${width}px`, async ({ page }, info) => {
    expect(new URL(info.project.use.baseURL as string).origin).toBe('http://127.0.0.1:3100');
    const state = JSON.parse(await readFile(path.join(root, 'state.json'), 'utf8'));
    const pm = state.accounts.pm;
    const errors: string[] = []; const api: Array<{ path: string; status: number }> = [];
    const assertFits = async () => expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.url().includes('/api/')) api.push({ path: new URL(response.url()).pathname, status: response.status() }); });
    await page.setViewportSize({ width, height: width < 500 ? 844 : 1000 });
    await page.goto('/login');
    await page.getByLabel('工号', { exact: false }).fill(pm.username);
    await page.getByLabel('密码', { exact: true }).fill(pm.password);
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await expect(page).toHaveURL(/\/dashboard$/);
    await expect(page.getByRole('heading', { name: '我的工作' })).toBeVisible();
    await page.getByRole('button', { name: '已完成', exact: true }).click();
    await expect(page.getByText('合成 R28 A 定制色', { exact: false }).first()).toBeVisible();
    await page.screenshot({ path: info.outputPath(`work-${width}.png`), fullPage: true });
    await assertFits();
    await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name: '颜色项目' }).click();
    await expect(page.getByRole('heading', { name: '颜色项目' })).toBeVisible();
    await expect(page.getByRole('link', { name: '合成 R28 A 定制色', exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath(`projects-${width}.png`), fullPage: true });
    await assertFits();
    await page.getByRole('link', { name: '合成 R28 A 定制色', exact: true }).click();
    await expect(page.getByRole('button', { name: '进度与任务', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: '资料', exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: '记录', exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath(`project-${width}.png`), fullPage: true });
    await assertFits();
    const workflowResponse = await page.request.get(`/api/workflows/projects/${state.projects.A}`);
    expect(workflowResponse.status()).toBe(200);
    const history = await workflowResponse.json();
    const initial = history.taskHistory.find((task: { nodeCode: string }) => task.nodeCode === 'PROJECT_INITIATION');
    await page.goto(`/projects/${state.projects.A}/tasks/${initial.id}`);
    await expect(page.getByText('当前为查看模式。', { exact: false })).toBeVisible();
    await page.getByText(/材料与版本记录/).click();
    await expect(page.getByRole('link', { name: '合成立项V1.pdf', exact: true })).toBeVisible();
    await expect(page.getByRole('link', { name: '合成立项V2.pdf', exact: true }).last()).toBeVisible();
    const workUrl = page.url();
    const content = page.waitForResponse(response => response.url().includes('/materials/') && response.url().includes('/content'));
    await page.getByRole('link', { name: '合成立项V1.pdf', exact: true }).click();
    const viewed = await content; expect(viewed.status()).toBe(200); expect(viewed.headers()['content-type']).toContain('application/pdf');
    await page.goto(workUrl); await expect(page.getByText('当前为查看模式。', { exact: false })).toBeVisible();
    await page.getByText(/材料与版本记录/).click();
    await page.screenshot({ path: info.outputPath(`task-${width}.png`), fullPage: true });
    await assertFits();
    expect(errors).toEqual([]);
    expect(api.some(item => item.path === '/api/auth/login' && item.status === 200)).toBe(true);
    expect(api.filter(item => item.status >= 500)).toEqual([]);
    await info.attach('native-network', { body: JSON.stringify({ width, api, errors }, null, 2), contentType: 'application/json' });
  });
}
